const BASE_COUNT: Record<Position, number> = {
  GK: 3,
  CB: 6,
  FB: 4,
  DM: 3,
  CM: 5,
  W: 4,
  ST: 3,
};

function buildRoster(hot: Position[], salt: number, bump: number): RosterCount[] {
  return POSITIONS.map((position, index) => {
    const count = BASE_COUNT[position] + bump + ((salt + index) % 3 === 0 ? 1 : 0);
    const hotRank = hot.indexOf(position);
    let graduating = (salt + index) % 2;
    if (hotRank === 0) graduating = Math.min(count - 1, 3);
    else if (hotRank === 1) graduating = Math.min(count - 1, 2);
    return { position, count, graduating: Math.max(0, Math.min(count, graduating)) };
  });
}

function slug(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '.')
    .replace(/^\.|\.$/g, '');
}

function campsFor(index: number): IdCamp[] {
  const winter = ['2026-12-05', '2026-12-12', '2027-01-09', '2027-01-16', '2027-02-06'][index % 5];
  const summer = ['2027-06-12', '2027-06-19', '2027-07-10', '2027-07-17'][index % 4];
  const list: IdCamp[] = [
    {
      name: 'Winter ID Camp',
      date: winter,
      notes: 'Sample camp listing. One field session and a campus tour.',
    },
  ];
  if (index % 3 !== 0) {
    list.push({
      name: 'Summer ID Camp',
      date: summer,
      notes: 'Sample overnight camp. Fictional date for the demo deck.',
    });
  }
  return list;
}

