function toProgram(seed: SchoolSeed, index: number): Program {
  const region = regionForState(seed.state);
  if (!region) throw new Error(`No region for ${seed.state}`);
  const coaches: Coach[] = seed.coaches.map(([name, title]) => ({
    id: slug(name),
    name,
    title,
    email: `${slug(name)}@${seed.id}.example.com`,
  }));
  const bump = seed.division === 'NCAA D1' ? 1 : 0;
  return {
    id: seed.id,
    sport: 'soccer',
    side: 'women',
    schoolName: seed.schoolName,
    division: seed.division,
    jucoDivision: seed.division === 'NJCAA' ? (JUCO_TIER[seed.id] ?? 'D1') : null,
    campusLife: CAMPUS_LIFE_BY_ID[seed.id] ?? ['close-knit', 'college-town'],
    conference: seed.conference,
    city: seed.city,
    state: seed.state,
    region,
    enrollment: seed.enrollment,
    acceptanceRate: seed.acceptanceRate,
    estimatedNetCost: seed.estimatedNetCost,
    schoolSize: schoolSizeFromEnrollment(seed.enrollment),
    academics: { avgGpa: seed.avgGpa, avgSat: seed.avgSat, avgAct: seed.avgAct },
    majors: seed.majors,
    roster: buildRoster(seed.hot, index + 1, bump),
    coaches,
    questionnaireUrl: `https://example.com/schools/${seed.id}/questionnaire`,
    admissionsUrl: `https://example.com/schools/${seed.id}/admissions`,
    costUrl: `https://example.com/schools/${seed.id}/cost`,
    athleticsUrl: `https://example.com/schools/${seed.id}/athletics`,
    idCamps: campsFor(index),
    sample: true,
  };
}

